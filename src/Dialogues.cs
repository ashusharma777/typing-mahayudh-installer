        public static int Total { get { return All.Values.Sum(a => a.Length); } }

        public static string Pick(string cat)
        {
            var arr = All[cat];
            if (!recent.ContainsKey(cat)) recent[cat] = new List<int>();
            var rec = recent[cat];
            int keep = Math.Min(arr.Length / 2, 8), i, guard = 0;
            do { i = rnd.Next(arr.Length); } while (rec.Contains(i) && guard++ < 50);
            rec.Add(i);
            while (rec.Count > keep) rec.RemoveAt(0);
            return arr[i];
        }

        public static string DashboardPick()
        {
            int days = (Cfg.ExamDate - DateTime.Today).Days;
            string[] pool = days <= 14 && days >= 0
                ? new[] { "exam", "exam", "daily", "discipline" }
                : new[] { "daily", "daily", "discipline", "comeback" };
            return Pick(pool[rnd.Next(pool.Length)]);
        }
